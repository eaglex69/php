-- Crownfall · схема MySQL 8 / MariaDB 10.4+
CREATE TABLE IF NOT EXISTS users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(40) NOT NULL UNIQUE,
  email VARCHAR(120) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(16) NOT NULL DEFAULT 'player',
  banned TINYINT(1) NOT NULL DEFAULT 0,
  gold INT NOT NULL DEFAULT 2500,
  gems INT NOT NULL DEFAULT 120,
  trophies INT NOT NULL DEFAULT 120,
  wins INT NOT NULL DEFAULT 0,
  losses INT NOT NULL DEFAULT 0,
  xp INT NOT NULL DEFAULT 0,
  clan_id INT NULL,
  last_gift_at DATETIME NULL,
  deck TEXT NOT NULL,
  battle_started_at DATETIME NULL,
  battle_mode VARCHAR(16) NOT NULL DEFAULT 'ladder',
  last_request_at DATETIME NULL,
  tournament_wins INT NOT NULL DEFAULT 0,
  tournament_claims INT NOT NULL DEFAULT 0,
  league_season VARCHAR(10) NOT NULL DEFAULT '',
  league_chest_season VARCHAR(10) NOT NULL DEFAULT '',
  pvp_opponent_id INT NULL,
  last_pvp_at DATETIME NULL,
  banner_skin VARCHAR(60) NOT NULL DEFAULT '',
  equipped_emotes TEXT NOT NULL,
  wildcards TEXT NOT NULL,
  evolution_fragments INT NOT NULL DEFAULT 0,
  cosmetics TEXT NOT NULL,
  tower_skin VARCHAR(60) NOT NULL DEFAULT 'classic',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_users_trophies (trophies)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS login_tokens (
  token VARCHAR(64) PRIMARY KEY,
  user_id INT NOT NULL,
  expires_at DATETIME NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_lt_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS clans (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(40) NOT NULL UNIQUE,
  description VARCHAR(255) NOT NULL DEFAULT '',
  badge VARCHAR(16) NOT NULL DEFAULT 'blue',
  owner_id INT NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS cards (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(80) NOT NULL UNIQUE,
  image VARCHAR(200) NOT NULL,
  rarity VARCHAR(20) NOT NULL DEFAULT 'Обычная',
  cost INT NOT NULL DEFAULT 3,
  damage INT NOT NULL DEFAULT 100,
  health INT NOT NULL DEFAULT 500,
  description TEXT NOT NULL,
  enabled TINYINT(1) NOT NULL DEFAULT 1,
  kind VARCHAR(12) NOT NULL DEFAULT 'ground',
  targets VARCHAR(12) NOT NULL DEFAULT 'ground',
  speed DOUBLE NOT NULL DEFAULT 1.3,
  rng DOUBLE NOT NULL DEFAULT 0.5,
  attack_speed DOUBLE NOT NULL DEFAULT 1.2,
  unit_count INT NOT NULL DEFAULT 1,
  splash DOUBLE NOT NULL DEFAULT 0,
  lifetime INT NOT NULL DEFAULT 0,
  ability VARCHAR(40) NOT NULL DEFAULT '',
  unlock_trophies INT NOT NULL DEFAULT 0,
  role VARCHAR(60) NOT NULL DEFAULT '',
  pros VARCHAR(255) NOT NULL DEFAULT '',
  cons VARCHAR(255) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS owned_cards (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  card_id INT NOT NULL,
  level INT NOT NULL DEFAULT 1,
  copies INT NOT NULL DEFAULT 0,
  UNIQUE KEY uq_owned (user_id, card_id),
  CONSTRAINT fk_oc_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_oc_card FOREIGN KEY (card_id) REFERENCES cards(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS clan_messages (
  id INT AUTO_INCREMENT PRIMARY KEY,
  clan_id INT NOT NULL,
  user_id INT NOT NULL,
  body VARCHAR(400) NOT NULL,
  kind VARCHAR(12) NOT NULL DEFAULT 'text',
  request_id INT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_cm_clan (clan_id, id),
  CONSTRAINT fk_cm_clan FOREIGN KEY (clan_id) REFERENCES clans(id) ON DELETE CASCADE,
  CONSTRAINT fk_cm_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS global_messages (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  body VARCHAR(300) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_gm_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS friends (
  id INT AUTO_INCREMENT PRIMARY KEY,
  requester_id INT NOT NULL,
  recipient_id INT NOT NULL,
  status VARCHAR(12) NOT NULL DEFAULT 'pending',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_friend (requester_id, recipient_id),
  CONSTRAINT fk_f_a FOREIGN KEY (requester_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_f_b FOREIGN KEY (recipient_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS card_requests (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  clan_id INT NOT NULL,
  card_id INT NOT NULL,
  amount INT NOT NULL,
  received INT NOT NULL DEFAULT 0,
  expires_at DATETIME NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_cr_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_cr_clan FOREIGN KEY (clan_id) REFERENCES clans(id) ON DELETE CASCADE,
  CONSTRAINT fk_cr_card FOREIGN KEY (card_id) REFERENCES cards(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS request_donations (
  id INT AUTO_INCREMENT PRIMARY KEY,
  request_id INT NOT NULL,
  donor_id INT NOT NULL,
  amount INT NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_rd_req FOREIGN KEY (request_id) REFERENCES card_requests(id) ON DELETE CASCADE,
  CONSTRAINT fk_rd_user FOREIGN KEY (donor_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS battles (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  opponent VARCHAR(60) NOT NULL,
  result VARCHAR(8) NOT NULL,
  crowns INT NOT NULL DEFAULT 0,
  trophies INT NOT NULL DEFAULT 0,
  gold INT NOT NULL DEFAULT 0,
  mode VARCHAR(16) NOT NULL DEFAULT 'ladder',
  opponent_id INT NULL,
  crowns_lost INT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_b_user (user_id, id),
  CONSTRAINT fk_b_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS pvp_matches (
  id INT AUTO_INCREMENT PRIMARY KEY,
  attacker_id INT NOT NULL,
  defender_id INT NOT NULL,
  attacker_crowns INT NOT NULL DEFAULT 0,
  defender_crowns INT NOT NULL DEFAULT 0,
  result VARCHAR(8) NOT NULL,
  trophies INT NOT NULL DEFAULT 0,
  seen TINYINT(1) NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_pvp_def (defender_id, seen),
  CONSTRAINT fk_pvp_a FOREIGN KEY (attacker_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_pvp_d FOREIGN KEY (defender_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS chests (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  type VARCHAR(16) NOT NULL DEFAULT 'silver',
  source VARCHAR(24) NOT NULL DEFAULT 'victory',
  rewards MEDIUMTEXT NULL,
  opened_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_chests_user (user_id, opened_at),
  CONSTRAINT fk_ch_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS leagues (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(60) NOT NULL UNIQUE,
  min_trophies INT NOT NULL DEFAULT 0,
  sort_order INT NOT NULL DEFAULT 0,
  chest_type VARCHAR(16) NOT NULL DEFAULT 'silver',
  reward_gold INT NOT NULL DEFAULT 0,
  reward_gems INT NOT NULL DEFAULT 0,
  color VARCHAR(16) NOT NULL DEFAULT 'blue',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS arenas (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(60) NOT NULL UNIQUE,
  min_trophies INT NOT NULL DEFAULT 0,
  difficulty INT NOT NULL DEFAULT 5,
  description VARCHAR(255) NOT NULL DEFAULT '',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tournaments (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  description VARCHAR(400) NOT NULL DEFAULT '',
  starts_at DATETIME NOT NULL,
  ends_at DATETIME NOT NULL,
  chest_type VARCHAR(16) NOT NULL DEFAULT 'tournament',
  auto TINYINT(1) NOT NULL DEFAULT 1,
  active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tournament_players (
  id INT AUTO_INCREMENT PRIMARY KEY,
  tournament_id INT NOT NULL,
  user_id INT NOT NULL,
  score INT NOT NULL DEFAULT 0,
  wins INT NOT NULL DEFAULT 0,
  battles INT NOT NULL DEFAULT 0,
  claimed TINYINT(1) NOT NULL DEFAULT 0,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_tp (tournament_id, user_id),
  CONSTRAINT fk_tp_t FOREIGN KEY (tournament_id) REFERENCES tournaments(id) ON DELETE CASCADE,
  CONSTRAINT fk_tp_u FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS cosmetic_items (
  id INT AUTO_INCREMENT PRIMARY KEY,
  type VARCHAR(12) NOT NULL,
  name VARCHAR(60) NOT NULL,
  rarity VARCHAR(20) NOT NULL DEFAULT 'Обычная',
  color1 VARCHAR(9) NOT NULL DEFAULT '#4aa8ff',
  color2 VARCHAR(9) NOT NULL DEFAULT '#1f4fa8',
  label VARCHAR(40) NOT NULL DEFAULT '',
  image VARCHAR(200) NOT NULL DEFAULT '',
  enabled TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_cos (type, name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS announcements (
  id INT AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(120) NOT NULL,
  body TEXT NOT NULL,
  active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS settings (
  k VARCHAR(60) PRIMARY KEY,
  v VARCHAR(255) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS audit_logs (
  id INT AUTO_INCREMENT PRIMARY KEY,
  admin_id INT NOT NULL,
  action VARCHAR(40) NOT NULL,
  detail VARCHAR(400) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
